//! `xtask i18n`: regenerates the Rust catalog from the String Catalog.

use std::collections::BTreeMap;
use std::fs;
use std::path::PathBuf;

use serde::Deserialize;

include!("../../crates/tabtool-i18n/strings/locales.rs");

pub fn run(check: bool) -> Result<(), String> {
    let generated = render_catalog()?;
    let output = catalog_path();
    if check {
        let existing = fs::read_to_string(&output)
            .map_err(|error| format!("cannot read {}: {error}", output.display()))?;
        if existing != generated {
            return Err(format!(
                "{} is out of date; run `cargo run -p xtask -- i18n`",
                output.display()
            ));
        }
        println!("{} is up to date", output.display());
    } else {
        fs::write(&output, generated)
            .map_err(|error| format!("cannot write {}: {error}", output.display()))?;
        println!("wrote {}", output.display());
    }
    Ok(())
}

fn catalog_path() -> PathBuf {
    crate::workspace_root().join("crates/tabtool-i18n/src/catalog.rs")
}

fn catalog_source_path() -> PathBuf {
    crate::repo_root().join("app/apple/Shared/Localizable.xcstrings")
}

fn overlay_path() -> PathBuf {
    crate::workspace_root().join("crates/tabtool-i18n/strings/universal.json")
}

#[derive(Deserialize)]
struct StringCatalog {
    strings: BTreeMap<String, CatalogEntry>,
}

#[derive(Deserialize)]
struct CatalogEntry {
    #[serde(default)]
    localizations: BTreeMap<String, Localization>,
}

#[derive(Deserialize)]
struct Localization {
    #[serde(rename = "stringUnit")]
    string_unit: Option<StringUnit>,
}

#[derive(Deserialize)]
struct StringUnit {
    value: String,
}

/// The overlay is `{"English key": {"fr": "...", ...}}`; a value replaces the
/// String Catalog translation and a new key adds strings the Apple catalog
/// does not have.
type Overlay = BTreeMap<String, BTreeMap<String, String>>;

fn read_catalog() -> Result<BTreeMap<String, BTreeMap<String, String>>, String> {
    let path = catalog_source_path();
    let bytes =
        fs::read(&path).map_err(|error| format!("cannot read {}: {error}", path.display()))?;
    let catalog: StringCatalog = serde_json::from_slice(&bytes)
        .map_err(|error| format!("cannot parse {}: {error}", path.display()))?;

    let mut strings = BTreeMap::new();
    for (key, entry) in catalog.strings {
        let mut translations = BTreeMap::new();
        for (locale, localization) in entry.localizations {
            if !LOCALES.contains(&locale.as_str()) {
                return Err(format!("{key}: unknown locale {locale}"));
            }
            if let Some(unit) = localization.string_unit {
                translations.insert(locale, unit.value);
            }
        }
        strings.insert(key, translations);
    }
    Ok(strings)
}

fn read_overlay() -> Result<Overlay, String> {
    let path = overlay_path();
    let bytes =
        fs::read(&path).map_err(|error| format!("cannot read {}: {error}", path.display()))?;
    serde_json::from_slice(&bytes)
        .map_err(|error| format!("cannot parse {}: {error}", path.display()))
}

fn merged_catalog() -> Result<BTreeMap<String, BTreeMap<String, String>>, String> {
    let mut strings = read_catalog()?;
    merge_overlay(&mut strings, read_overlay()?)?;
    validate_complete(&strings)?;
    Ok(strings)
}

/// Applies the overlay: a value replaces the String Catalog translation, and
/// a new key adds a string the Apple catalog does not have.
fn merge_overlay(
    strings: &mut BTreeMap<String, BTreeMap<String, String>>,
    overlay: Overlay,
) -> Result<(), String> {
    for (key, translations) in overlay {
        for (locale, value) in translations {
            if !LOCALES.contains(&locale.as_str()) {
                return Err(format!("{key}: unknown overlay locale {locale}"));
            }
            strings
                .entry(key.clone())
                .or_default()
                .insert(locale, value);
        }
    }
    Ok(())
}

fn validate_complete(strings: &BTreeMap<String, BTreeMap<String, String>>) -> Result<(), String> {
    let mut missing = Vec::new();
    for (key, translations) in strings {
        for locale in LOCALES {
            if translations.get(locale).is_none_or(String::is_empty) {
                missing.push(format!("{locale}: {key}"));
            }
        }
    }
    if !missing.is_empty() {
        return Err(format!(
            "the catalog is missing {} translation(s):\n{}",
            missing.len(),
            missing.join("\n")
        ));
    }
    Ok(())
}

fn render_catalog() -> Result<String, String> {
    let strings = merged_catalog()?;
    let mut output = String::from(
        "// @generated by `cargo run -p xtask -- i18n`. Do not edit by hand.\n\
         //\n\
         // Source: app/apple/Shared/Localizable.xcstrings and strings/universal.json.\n\n",
    );
    output.push_str("#[rustfmt::skip]\n");
    output.push_str("pub(crate) static ENTRIES: &[(&str, &[(&str, &str)])] = &[\n");
    for (key, translations) in &strings {
        output.push_str(&format!("    ({key:?}, &["));
        for (index, locale) in LOCALES.iter().enumerate() {
            if index > 0 {
                output.push_str(", ");
            }
            let value = translations
                .get(*locale)
                .ok_or_else(|| format!("{key}: no {locale} translation"))?;
            output.push_str(&format!("({locale:?}, {value:?})"));
        }
        output.push_str("]),\n");
    }
    output.push_str("];\n\n");
    output.push_str(
        r#"pub(crate) fn translation(key: &str, code: &str) -> Option<&'static str> {
    let entry = ENTRIES
        .binary_search_by(|entry| entry.0.cmp(key))
        .ok()
        .map(|index| &ENTRIES[index])?;
    entry
        .1
        .iter()
        .find(|(locale, _)| *locale == code)
        .map(|(_, value)| *value)
}
"#,
    );
    Ok(output)
}

#[cfg(test)]
mod tests {
    use std::collections::{BTreeMap, BTreeSet};

    use super::{LOCALES, Overlay, merge_overlay, render_catalog, validate_complete};

    #[test]
    fn the_generated_catalog_covers_every_key_in_every_locale() {
        let catalog = render_catalog().expect("the source catalog is complete");
        assert!(catalog.contains("(\"Cancel\", &["));
        assert!(catalog.contains("(\"CSV\", &["));
        for locale in LOCALES {
            assert!(catalog.contains(&format!("({locale:?}, ")), "{locale}");
        }
    }

    #[test]
    fn the_shared_locale_list_is_unique() {
        let unique: BTreeSet<_> = LOCALES.iter().collect();
        assert_eq!(unique.len(), 11);
    }

    #[test]
    fn an_overlay_replaces_a_translation_and_adds_a_key() {
        let mut catalog = BTreeMap::new();
        let cancel = LOCALES
            .iter()
            .map(|locale| (locale.to_string(), "Cancel".to_string()))
            .collect();
        catalog.insert("Cancel".to_string(), cancel);

        let mut overlay: Overlay = BTreeMap::new();
        overlay.insert(
            "Cancel".to_string(),
            BTreeMap::from([("fr".to_string(), "Annuler !".to_string())]),
        );
        overlay.insert(
            "CSV".to_string(),
            LOCALES
                .iter()
                .map(|locale| (locale.to_string(), "CSV".to_string()))
                .collect(),
        );

        merge_overlay(&mut catalog, overlay).expect("the overlay is valid");
        assert_eq!(catalog["Cancel"]["fr"], "Annuler !");
        assert_eq!(catalog["Cancel"]["de"], "Cancel");
        assert_eq!(catalog["CSV"]["zh-Hans"], "CSV");
        validate_complete(&catalog).expect("the merged catalog is complete");
    }

    #[test]
    fn an_incomplete_catalog_is_rejected() {
        let mut catalog = BTreeMap::new();
        catalog.insert(
            "Only English".to_string(),
            BTreeMap::from([("en".to_string(), "Only English".to_string())]),
        );
        assert!(validate_complete(&catalog).is_err());
    }
}
